CATEGORY_MAP = {
    'Двигатель': 'engine',
    'Трансмиссия': 'transmission',
    'Тормозная система': 'brakes',
    'Подвеска': 'suspension',
    'Электрика': 'electrics',
    'Кузовные детали': 'body'
}

MANUFACTURERS = ['Bosch', 'NGK', 'Febest', 'Mann-Filter', 'Lemförder', 'TRW', 'Brembo', 'KYB', 'Varta', 'Оригинал']

def generate_part(category_ru, name):
    """Генерирует одну запчасть"""
    # Берём первые 3 буквы категории для артикула
    prefix = CATEGORY_MAP[category_ru][:3].upper()
    if len(prefix) < 3:
        prefix = prefix.ljust(3, 'X')
    
    return {
        'name': name,
        'category': CATEGORY_MAP[category_ru],
        'manufacturer': random.choice(MANUFACTURERS),
        'sku': f"{prefix}{random.randint(10000, 99999)}",
        'price': round(random.uniform(15, 500), 2),
        'stock': random.randint(5, 50),
        'description': f"{name} в наличии. Гарантия качества. Доставка по Минску и всей Беларуси.",
        'compatibility': random.choice(['', 'Toyota Corolla 2008-2015', 'VW Golf 2010-2017', 'Renault Logan', 'BMW X5 E70', 'Audi A4 B8', 'Lada Vesta', 'Ford Focus 2'])
    }

def main():
    print("=" * 60)
    print("🚗 ГЕНЕРАТОР ТЕСТОВЫХ ДАННЫХ (90 ЗАПЧАСТЕЙ)")
    print("=" * 60)
    
    all_data = {}
    total = 0
    
    for category_ru, names in PARTS_DATA.items():
        parts = []
        for name in names[:15]:  # Берём первые 15 названий
            part = generate_part(category_ru, name)
            parts.append(part)
            print(f"   ✅ {category_ru}: {part['name']} — {part['price']} BYN")
        
        all_data[category_ru] = parts
        total += len(parts)
        
        # Сохраняем по категориям
        with open(f'parts_{category_ru}.json', 'w', encoding='utf-8') as f:
            json.dump(parts, f, ensure_ascii=False, indent=2)
    
    # Сохраняем всё вместе
    with open('all_parts.json', 'w', encoding='utf-8') as f:
        json.dump(all_data, f, ensure_ascii=False, indent=2)
    
    print("\n" + "=" * 60)
    print(f"✅ Создано {total} запчастей!")
    print("📁 Файлы сохранены:")
    print("   - all_parts.json")
    for cat in PARTS_DATA.keys():
        print(f"   - parts_{cat}.json")
    print("=" * 60)

if __name__ == "__main__":
    main()